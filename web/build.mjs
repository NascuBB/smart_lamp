import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { gzipSync, constants } from 'node:zlib';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { minify as minifyHtml } from 'html-minifier-terser';
import { minify as minifyJs } from 'terser';
import CleanCSS from 'clean-css';

const webDir = path.dirname(fileURLToPath(import.meta.url));
const outputFile = path.join(webDir, '..', 'WebAssets.h');

const pages = [
  { route: '/', file: 'pages/index.html' },
  { route: '/settings', file: 'pages/settings.html' },
  { route: '/saved_networks', file: 'pages/saved_networks.html' },
];

const read = (file) => readFile(path.join(webDir, file), 'utf8');
const shortHash = (text) => createHash('sha256').update(text).digest('hex').slice(0, 8);
const gzip = (text) => gzipSync(Buffer.from(text, 'utf8'), { level: constants.Z_BEST_COMPRESSION });

async function buildCommonAssets() {
  const css = new CleanCSS({ level: 2 }).minify(await read('common.css'));
  if (css.errors.length) throw new Error(css.errors.join('\n'));

  const js = await minifyJs(await read('common.js'), { toplevel: false, compress: true, mangle: true });

  return [
    { route: '/common.css', type: 'text/css', text: css.styles, immutable: true },
    { route: '/common.js', type: 'application/javascript', text: js.code, immutable: true },
  ];
}

async function buildPages(common) {
  let template = await read('template.html');
  for (const asset of common) {
    template = template.replace(`"${asset.route}"`, `"${asset.route}?v=${shortHash(asset.text)}"`);
  }

  const result = [];
  for (const page of pages) {
    const html = template.replace('<!-- PAGE -->', await read(page.file));
    const text = await minifyHtml(html, {
      collapseWhitespace: true,
      removeComments: true,
      removeRedundantAttributes: true,
      removeScriptTypeAttributes: true,
      useShortDoctype: true,
      minifyCSS: { level: 2 },
      minifyJS: { toplevel: true, compress: true, mangle: true },
    });
    result.push({ route: page.route, type: 'text/html', text, immutable: false });
  }
  return result;
}

function toCArray(name, bytes) {
  const lines = [];
  for (let i = 0; i < bytes.length; i += 20) {
    lines.push('  ' + [...bytes.subarray(i, i + 20)].map((b) => `0x${b.toString(16).padStart(2, '0')}`).join(', '));
  }
  return `static const uint8_t ${name}[] PROGMEM = {\n${lines.join(',\n')}\n};\n`;
}

const common = await buildCommonAssets();
const assets = [...await buildPages(common), ...common];

let arrays = '';
const entries = [];
let sourceTotal = 0;
let gzipTotal = 0;

for (const [index, asset] of assets.entries()) {
  const compressed = gzip(asset.text);
  const name = `webAsset${index}`;
  arrays += toCArray(name, compressed) + '\n';
  entries.push(`  {"${asset.route}", "${asset.type}", ${name}, sizeof(${name}), ${asset.immutable}},`);
  sourceTotal += Buffer.byteLength(asset.text);
  gzipTotal += compressed.length;
  console.log(`${asset.route.padEnd(16)} ${String(Buffer.byteLength(asset.text)).padStart(6)} B minified -> ${String(compressed.length).padStart(6)} B gzip`);
}

console.log(`${'total'.padEnd(16)} ${String(sourceTotal).padStart(6)} B minified -> ${String(gzipTotal).padStart(6)} B gzip`);

const header = `#ifndef WEB_ASSETS_H
#define WEB_ASSETS_H

// Generated by web/build.mjs from the files in web/. Do not edit.

#include <Arduino.h>

struct WebAsset {
  const char* path;
  const char* contentType;
  const uint8_t* data;
  size_t length;
  bool immutable;
};

${arrays}static const WebAsset WEB_ASSETS[] = {
${entries.join('\n')}
};

static const size_t WEB_ASSET_COUNT = sizeof(WEB_ASSETS) / sizeof(WEB_ASSETS[0]);

#endif
`;

await writeFile(outputFile, header);
console.log(`Wrote ${path.relative(process.cwd(), outputFile)}`);
